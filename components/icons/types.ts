// Shared props for the Lucide icon components in this folder (one file per icon).
export type IconProps = {
  /** Square edge length in px. Default 22. */
  size?: number;
  /** Stroke colour. Default is the theme ink colour (#1D1D1F). */
  color?: string;
  /** Stroke width in viewBox units. Default 1.8. */
  strokeWidth?: number;
};
